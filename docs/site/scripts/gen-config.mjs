// Writes src/content/docs/configuration.md from the table in server/src/envvars.ts.
//   node scripts/gen-config.mjs           write the page
//   node scripts/gen-config.mjs --check   exit 1 when the page on disk is stale
// The server test (server/src/__tests__/envvars.test.ts) runs the same check.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { ENV_VARS } from '../../../server/src/envvars.ts'

export const pagePath = fileURLToPath(new URL('../src/content/docs/configuration.md', import.meta.url))

const GROUPS = [
  ['Folders', 'Folders'],
  ['Games and catalog', 'Games and catalog'],
  ['Images and saves', 'Images and saves'],
  ['Behind a proxy', 'Behind a proxy'],
  ['Server', 'Server'],
]

function shownDefault(v) {
  if (v.shown) return v.shown
  if (v.fallback === '') return 'empty'
  return '`' + String(v.fallback) + '`'
}

export function render() {
  const out = []
  out.push(`---
title: Configuration
description: Every environment variable Renplay reads, with its default.
---

<!-- Generated by docs/site/scripts/gen-config.mjs from server/src/envvars.ts. Do not edit by hand. -->

Renplay works without any configuration. These environment variables are for special setups. Set
them on the container, for example with \`-e RENPLAY_IMAGE_QUALITY=80\` or in the \`environment:\`
block of a Compose file.

A variable that is empty counts as not set. The container runs as any non-root user and with a
read-only root filesystem, so any folder you point a variable at must be writable by that user.
`)
  for (const [group, title] of GROUPS) {
    const rows = ENV_VARS.filter((v) => v.group === group)
    if (!rows.length) continue
    out.push(`## ${title}\n`)
    for (const v of rows) out.push(`<div class="config-entry" id="${v.name.toLowerCase().replaceAll('_', '-')}">\n\n**\`${v.name}\`**\n\n<div class="config-default">\n\nDefault: ${shownDefault(v)}\n\n</div>\n\n${v.description}\n\n</div>\n`)
    out.push('')
  }
  out.push(`## Folders inside the container

| Folder | What is in it |
|---|---|
| \`/data\` | Saves and their history, accounts, the SQLite library, mods, covers, walkthroughs. **Local disk only. Back this up.** |
| \`/downloads\` | Optional downloads and drop folder. Used when it exists and is writable, or when selected with \`ARCHIVES_DIR\`. Downloads are kept by default. \`RENPLAY_KEEP_DOWNLOADS=false\` deletes only unchanged completed uploads after a successful install. Files copied in are never deleted automatically. |
| \`/games/_archives\` | Downloads when no usable \`/downloads\` exists. Existing files are never moved. |
| \`/games\` (the rest) | Installed games, engines and scratch space. Scratch stays on this filesystem for atomic installs. Rebuilding requires the original downloads. |

Deleting \`/data\` loses saves and the library. Deleting \`/games\` also loses downloads stored
inside it. Deleting a download means reinstalling needs that download again. Settings shows
the downloads folder in use.
`)
  return out.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render()
  if (process.argv.includes('--check')) {
    let have = ''
    try {
      have = readFileSync(pagePath, 'utf8')
    } catch {}
    if (have !== text) {
      console.error('configuration.md is stale. Run: cd docs/site && npm run gen')
      process.exit(1)
    }
    console.log('configuration.md is up to date')
  } else {
    writeFileSync(pagePath, text)
    console.log('wrote', pagePath)
  }
}
